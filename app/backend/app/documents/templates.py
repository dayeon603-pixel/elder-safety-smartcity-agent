"""공문 초안 templates per action_id: who receives it, what is asked, which numbers justify it.

Every draft states that it was generated by the system and has no effect before a 담당자 reviews and
signs it. Numbers come from the recommendation's `evidence` (modules/evidence.py) and the action payload;
nothing is invented here.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from ..heat.ranktext import expected_cases_text

SENDER = "고령자 안전 스마트도시 에이전트 (시스템 생성 초안)"
FOOTER = ("본 문서는 고령자 안전 스마트도시 에이전트가 공개 데이터와 모델 산출값으로 자동 생성한 초안입니다. 담당자의 검토·결재 전에는 효력이 없으며, "
          "어떤 외부 시스템으로도 전송되지 않았습니다. 스마트도시 통합플랫폼 연계(TTA 연계규격)는 다음 단계이며 본 초안은 그 규격을 따른다고 주장하지 않습니다.")
NA = "자료 없음"


@dataclass(frozen=True, slots=True)
class DocSpec:
    title: str
    recipient: str
    subject: str


ACTION_DOCS: dict[str, DocSpec] = {
    "signals": DocSpec("보행신호 시간 연장 협조 요청", "관할 경찰서 교통과 / 도로교통공단", "폭염 위험일 고령자 보행신호 연장"),
    "silver.check": DocSpec("노인보호구역(실버존) 지정 검토 요청", "구청 교통행정과 / 도로관리청", "2024 사고다발지 기준 실버존 후보 현장 확인"),
    "cbs": DocSpec("재난문자(CBS) 송출 요청", "재난안전대책본부 상황실", "폭염 위험 시군구 재난문자 초안 송출"),
    "bit": DocSpec("버스정류장 안내단말(BIT) 표출 요청", "교통정보센터 / 시내버스 운영과", "폭염 안내 문구 정류장 표출"),
    "route": DocSpec("독거노인 방문 점검 협조 요청", "주민센터 / 노인맞춤돌봄 수행기관", "폭염 위험일 방문 동선에 따른 점검"),
    "heat.alert": DocSpec("폭염 경보 대상 추가 검토 요청", "재난안전대책본부", "현행 기준이 놓친 시군구의 경보 대상 추가"),
    "heat.teams": DocSpec("방문 점검팀 배치 협조 요청", "보건소 / 노인맞춤돌봄 수행기관", "예상 환자 수 기준 방문팀 배치"),
    "aed.convert": DocSpec("AED 24시간 개방 전환 요청", "응급의료지원센터 / 시설 관리자", "밤 공백 상위 구 AED 24시간 전환"),
}


def _temp(ev: dict[str, Any]) -> str:
    if ev.get("apparent_max_c") is not None:
        return f"체감 최고 {ev['apparent_max_c']}℃"
    if ev.get("tmax_c") is not None:
        return f"최고기온 {ev['tmax_c']}℃"
    return NA


def evidence_rows(ev: dict[str, Any]) -> list[tuple[str, str]]:
    """Two-column rows for the 근거 table (only values that exist)."""
    rows: list[tuple[str, str]] = [("기준일", str(ev.get("date", NA)))]
    lam = ev.get("expected_cases_lambda")
    rows.append(("예상 온열질환자 수(λ)", f"{lam:.2f}명" if isinstance(lam, (int, float)) else NA))
    rows.append(("65세 이상 인구", f"{int(ev['pop65']):,}명" if ev.get("pop65") is not None else NA))
    rows.append(("기온", _temp(ev)))
    station = ev.get("station") or {}
    if station.get("id"):
        rows.append(("관측 지점", f"기상청 ASOS {station.get('name') or station['id']} ({station.get('dist_km')} km)"))
    if ev.get("rank") is not None and ev.get("n_cells"):
        rows.append(("에이전트 위험 순위", f"{ev['n_cells']}곳 중 {ev['rank']}위"))
    if ev.get("alerted") is not None:
        rows.append(("에이전트 경보 여부", "경보 대상" if ev["alerted"] else "경보 대상 아님"))
    for name, sha in (ev.get("data_sha256") or {}).items():
        rows.append((f"데이터 {name}", f"sha256 {sha[:16]}…"))
    if ev.get("model"):
        rows.append(("모델", str(ev["model"])))
    return rows


def render(action_id: str, region_name: str, date: str, ev: dict[str, Any], payload: dict[str, Any],
           sources: dict[str, str] | None = None) -> tuple[str, list[tuple[str, str]], list[str], list[tuple[str, str]], str]:
    """(title, meta rows, body paragraphs, evidence rows, footer) for `build_docx`.

    `payload` carries the action-specific facts: cbs text, bit stops/lines, signals, route stops, candidates.

    Raises:
        KeyError: unknown action_id.
    """
    spec = ACTION_DOCS[action_id]
    meta = [("수신", spec.recipient), ("발신", SENDER), ("제목", f"{region_name} {spec.subject}"), ("기준일", date)]
    body: list[str] = [f"1. {region_name}의 {date} 생활안전 지표를 검토한 결과 아래와 같이 요청드립니다."]
    temp = _temp(ev)
    lam = ev.get("expected_cases_lambda")
    lam_txt = ("예상 온열질환자 " + expected_cases_text(float(lam), ev.get("apparent_max_c"), 2)[0].removeprefix("예상 환자 ")
               if isinstance(lam, (int, float)) else "예상 환자 수 자료 없음")
    if action_id == "signals":
        items = payload.get("signals") or []
        ids = ", ".join(str(s.get("crosswalk_id", "")) for s in items[:5])
        body.append(f"2. 65세 이상 밀집 행정동의 횡단보도 {len(items)}곳에 대해 보행신호 연장(건당 +{items[0].get('extend_s') if items else '-'}초)을 "
                    f"요청합니다. 대상: {ids or NA}.")
    elif action_id == "silver.check":
        body.append(f"2. 2024년 사고다발지 {payload.get('hotspots_2024', NA)}곳 중 300m 안에 보호구역이 있는 곳은 현행 "
                    f"{payload.get('covered_current', NA)}곳, 에이전트 후보 적용 시 {payload.get('covered_ours', NA)}곳입니다. "
                    f"에이전트 후보 {payload.get('our_picks', NA)}곳의 현장 확인을 요청합니다.")
    elif action_id == "cbs":
        body.append(f"2. 아래 재난문자 초안({payload.get('length', '-')}자, 한도 {payload.get('limit', '-')}자)의 송출을 검토해 주십시오.")
        body.append(f"   「{payload.get('text', '')}」")
        if payload.get("easy_text"):
            body.append(f"   쉬운 말 버전: 「{payload['easy_text']}」")
    elif action_id == "bit":
        stops = payload.get("stops") or []
        names = ", ".join(str(s.get("name", "")) for s in stops[:5])
        lines = " / ".join(payload.get("lines") or [])
        body.append(f"2. 65세 이상 도달 인구가 가장 큰 정류장 {len(stops)}곳({names})에 다음 2줄 문구 표출을 요청합니다: 「{lines}」.")
    elif action_id == "route":
        stops = payload.get("stops") or []
        body.append(f"2. 65세 이상 인구 순 방문 동선 {len(stops)}개 지점(총 {payload.get('km', '-')} km, 직선거리 기준)에 따른 "
                    f"방문 점검 협조를 요청합니다.")
    elif action_id == "heat.alert":
        body.append(f"2. 이 시군구는 폭염 위험 모델 기준 경보 대상이나 현행 기준에서는 제외되어 있습니다 ({lam_txt}, {temp}). 경보 대상 추가 검토를 요청합니다.")
    elif action_id == "heat.teams":
        body.append(f"2. 예상 환자 수 기준으로 방문팀 {payload.get('teams', '-')}팀(전체 {payload.get('teams_total', '-')}팀 중) 배치를 요청합니다 ({lam_txt}).")
    elif action_id == "aed.convert":
        cand = payload.get("candidate") or {}
        body.append(f"2. 밤(22~06시) AED 열림 비율 {payload.get('night_open_share_pct', '-')}% (낮 {payload.get('day_open_share_pct', '-')}%)로 "
                    f"공백이 큽니다. 1순위 후보 「{cand.get('org', NA)}」({cand.get('place', '')}, 평일 {cand.get('weekday_hours') or '시간 정보 없음'})의 "
                    f"24시간 개방 전환을 요청합니다.")
    body.append(f"3. 판단 근거: {lam_txt}, {temp}, 65세 이상 {int(ev['pop65']):,}명." if ev.get("pop65") is not None
                else f"3. 판단 근거: {lam_txt}, {temp}.")
    if sources:
        body.append("4. 출처: " + " · ".join(f"{k}: {v}" for k, v in sources.items()))
    return f"{spec.title} (초안)", meta, body, evidence_rows(ev), FOOTER


__all__ = ["ACTION_DOCS", "FOOTER", "SENDER", "evidence_rows", "render"]
