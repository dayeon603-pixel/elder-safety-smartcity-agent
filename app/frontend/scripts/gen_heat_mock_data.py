"""
Writes src/api/heatMockData.ts from the real experiment outputs, so dev mocks carry the exact published numbers:
  - eval rows (per year + pooled 2023-25, variants F/O) from experiments/heat/out/results.json
  - 251 district units (2026 names, centroid, population, 65+ share) and the representative-day alerts
    from experiments/heat/out/map_day_2025_F.csv
Usage: python3 scripts/gen_heat_mock_data.py [out_dir] [dest]
"""
import csv
import json
import sys
from pathlib import Path

OUT = Path(sys.argv[1] if len(sys.argv) > 1 else "../backend/experiments/heat/out")
DEST = Path(sys.argv[2] if len(sys.argv) > 2 else "src/api/heatMockData.ts")
BUDGET = "B1|per_day"
METHODS = ["B1", "B1S", "B2", "HEUR", "OURS"]
POOLED_YEAR = 0  # must equal POOLED_YEAR in src/lib/heatEval.ts


def rows_for(variant: str, year: int, block: dict) -> list[list]:
    out = []
    for m in METHODS:
        c = block["methods"][m]["capture"]
        d = None
        if m != "B1":
            e = block["delta"][f"{m}-B1"]["capture"]
            d = [round(e["est"], 4), round(e["lo"], 4), round(e["hi"], 4)]
        out.append([variant, year, m, round(c["est"], 4), round(c["lo"], 4), round(c["hi"], 4), d])
    return out


res = json.loads((OUT / "results.json").read_text(encoding="utf-8"))
eval_rows: list[list] = []
for v in ("F", "O"):
    vr = res["variants"][v]
    for y in sorted(vr["folds"]):
        eval_rows += rows_for(v, int(y), vr["folds"][y]["budget"][BUDGET])
    eval_rows += rows_for(v, POOLED_YEAR, vr["pooled_2023_2025"][BUDGET])

with (OUT / "map_day_2025_F.csv").open(encoding="utf-8-sig") as f:
    day = list(csv.DictReader(f))
date = day[0]["date"]
regions = [
    [f"{int(r['region_code']):05d}", r["sido"], r["sgg"], round(float(r["lat"]), 4), round(float(r["lon"]), 4),
     int(float(r["pop"])), round(float(r["old_share"]), 4)]
    for r in day
]
rep = [
    [f"{int(r['region_code']):05d}", int(r["b1_alerted"]), int(r["ours_alerted"]), int(float(r["cases"])),
     round(float(r["ours_pred_cases"]), 4), float(r["tmax_d"])]
    for r in day
]

js = lambda x: json.dumps(x, ensure_ascii=False, separators=(",", ":"))
DEST.write_text(
    "/* GENERATED by scripts/gen_heat_mock_data.py from experiments/heat/out. Do not edit. */\n"
    "export type MockEvalTuple = readonly [string, number, string, number, number, number, readonly [number, number, number] | null];\n"
    f"export const MOCK_EVAL: readonly MockEvalTuple[] = {js(eval_rows)};\n"
    "/** [code, sido, name, lat, lon, pop, old_share] */\n"
    f"export const MOCK_UNITS: readonly (readonly [string, string, string, number, number, number, number])[] = {js(regions)};\n"
    f"export const REP_DATE = {js(date)};\n"
    "/** Representative day: [code, b1_alerted, ours_alerted, cases, ours_score, tmax] */\n"
    f"export const REP_DAY: readonly (readonly [string, number, number, number, number, number])[] = {js(rep)};\n",
    encoding="utf-8",
)
print(f"{len(eval_rows)} eval rows, {len(regions)} units, rep day {date} -> {DEST}")
