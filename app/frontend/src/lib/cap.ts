/**
 * Common Alerting Protocol 1.2 (OASIS) message builder for the field drill. status=Exercise, scope=Restricted.
 * Produces the XML and an equivalent JSON object. Nothing is transmitted.
 */
import { CAP_KST_OFFSET_MIN, CAP_LANGUAGE, CAP_RADIUS_KM, CAP_SENDER } from "../config";

export const CAP_NAMESPACE = "urn:oasis:names:tc:emergency:cap:1.2";

export interface CapInput {
  identifier: string;
  sent: Date;
  event: string;
  headline: string;
  description: string;
  instruction: string;
  areaDesc: string;
  lat: number;
  lon: number;
  radiusKm?: number;
  /** Restricted-scope recipients text (CAP requires <restriction> when scope=Restricted). */
  restriction?: string;
  note?: string;
}

export interface CapJson {
  alert: {
    xmlns: string;
    identifier: string;
    sender: string;
    sent: string;
    status: "Exercise";
    msgType: "Alert";
    scope: "Restricted";
    restriction: string;
    note: string;
    info: {
      language: string;
      category: ["Health", "Safety"];
      event: string;
      urgency: "Immediate";
      severity: "Severe";
      certainty: "Possible";
      headline: string;
      description: string;
      instruction: string;
      area: { areaDesc: string; circle: string };
    };
  };
}

/** CAP dateTime: ISO 8601 with a numeric offset; "Z" is not allowed by the spec. */
export function capDateTime(d: Date, offsetMin: number = CAP_KST_OFFSET_MIN): string {
  const shifted = new Date(d.getTime() + offsetMin * 60_000);
  const sign = offsetMin >= 0 ? "+" : "-";
  const abs = Math.abs(offsetMin);
  const hh = String(Math.floor(abs / 60)).padStart(2, "0");
  const mm = String(abs % 60).padStart(2, "0");
  return `${shifted.toISOString().slice(0, 19)}${sign}${hh}:${mm}`;
}

export function escapeXml(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&apos;");
}

function validate(input: CapInput): void {
  if (!Number.isFinite(input.lat) || input.lat < -90 || input.lat > 90) throw new RangeError("lat out of range");
  if (!Number.isFinite(input.lon) || input.lon < -180 || input.lon > 180) throw new RangeError("lon out of range");
  if (input.identifier.trim() === "" || /[\s,<&]/.test(input.identifier)) throw new RangeError("identifier must be non-empty without whitespace, commas, < or &");
  if (input.radiusKm !== undefined && !(input.radiusKm >= 0)) throw new RangeError("radiusKm must be >= 0");
}

export function buildCapJson(input: CapInput): CapJson {
  validate(input);
  const radius = input.radiusKm ?? CAP_RADIUS_KM;
  return {
    alert: {
      xmlns: CAP_NAMESPACE,
      identifier: input.identifier,
      sender: CAP_SENDER,
      sent: capDateTime(input.sent),
      status: "Exercise",
      msgType: "Alert",
      scope: "Restricted",
      restriction: input.restriction ?? "시뮬레이션 훈련 메시지 · 외부 전송 안 함",
      note: input.note ?? "This is an exercise message generated by a simulation; it was not transmitted.",
      info: {
        language: CAP_LANGUAGE,
        category: ["Health", "Safety"],
        event: input.event,
        urgency: "Immediate",
        severity: "Severe",
        certainty: "Possible",
        headline: input.headline,
        description: input.description,
        instruction: input.instruction,
        area: { areaDesc: input.areaDesc, circle: `${input.lat},${input.lon} ${radius}` },
      },
    },
  };
}

export function buildCapXml(input: CapInput): string {
  const a = buildCapJson(input).alert;
  const i = a.info;
  const e = escapeXml;
  return [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<alert xmlns="${a.xmlns}">`,
    `  <identifier>${e(a.identifier)}</identifier>`,
    `  <sender>${e(a.sender)}</sender>`,
    `  <sent>${a.sent}</sent>`,
    `  <status>${a.status}</status>`,
    `  <msgType>${a.msgType}</msgType>`,
    `  <scope>${a.scope}</scope>`,
    `  <restriction>${e(a.restriction)}</restriction>`,
    `  <note>${e(a.note)}</note>`,
    `  <info>`,
    `    <language>${i.language}</language>`,
    ...i.category.map((c) => `    <category>${c}</category>`),
    `    <event>${e(i.event)}</event>`,
    `    <urgency>${i.urgency}</urgency>`,
    `    <severity>${i.severity}</severity>`,
    `    <certainty>${i.certainty}</certainty>`,
    `    <headline>${e(i.headline)}</headline>`,
    `    <description>${e(i.description)}</description>`,
    `    <instruction>${e(i.instruction)}</instruction>`,
    `    <area>`,
    `      <areaDesc>${e(i.area.areaDesc)}</areaDesc>`,
    `      <circle>${i.area.circle}</circle>`,
    `    </area>`,
    `  </info>`,
    `</alert>`,
  ].join("\n");
}
