"""Search and download real photographs from Wikimedia Commons with credits.

Usage:
    fetch_photo.py search "<query>" -n 8
    fetch_photo.py get "File:Name.jpg" --out /path/to/assets/
"""
from __future__ import annotations

import argparse
import html
import json
import logging
import re
import sys
import urllib.error
import urllib.parse
import urllib.request
from dataclasses import dataclass
from pathlib import Path
from typing import Any

LOG = logging.getLogger("fetch_photo")

API_URL = "https://commons.wikimedia.org/w/api.php"
USER_AGENT = (
    "KCF-HackathonDeckTools/1.0 (https://github.com/dayeon603-pixel; "
    "dayeon603@gmail.com) python-urllib"
)
THUMB_WIDTH = 1920
FILE_NAMESPACE = 6
OVERFETCH_FACTOR = 4
MAX_API_LIMIT = 50
HTTP_TIMEOUT_S = 60
ALLOWED_MIME = frozenset({"image/jpeg"})
CREDITS_FILENAME = "CREDITS.md"
CREDITS_HEADER = (
    "# Photo credits\n\n"
    "| file | author | license | license URL | source |\n"
    "|---|---|---|---|---|\n"
)
# Order matters only for readability; each is matched against the normalised name.
ALLOWED_LICENSE_PATTERNS: tuple[re.Pattern[str], ...] = (
    re.compile(r"^cc0\b"),
    re.compile(r"^cc[- ]?zero\b"),
    re.compile(r"^public domain\b"),
    re.compile(r"^pd\b"),
    re.compile(r"^cc[- ]by[- ]sa\b"),
    re.compile(r"^cc[- ]by\b(?![- ](nc|nd))"),
)
AI_PATTERN = re.compile(
    r"ai[- ]generated|artificial intelligence|midjourney|stable diffusion|"
    r"dall[-· ]?e|generated by ai|ai-created|\bAI art\b",
    re.IGNORECASE,
)
TAG_PATTERN = re.compile(r"<[^>]+>")
SPACE_PATTERN = re.compile(r"\s+")


class FetchError(RuntimeError):
    """Raised when Commons cannot be reached or returns unusable data."""


class LicenseRefused(FetchError):
    """Raised when a file's license is not on the allow-list."""


@dataclass(frozen=True)
class Photo:
    """A Commons photograph candidate."""

    title: str
    width: int
    height: int
    author: str
    license_short: str
    license_url: str
    thumb_url: str
    page_url: str
    mime: str
    ai_flagged: bool


def strip_html(raw: str) -> str:
    """Remove tags and entities from Commons metadata values."""
    text = html.unescape(TAG_PATTERN.sub("", raw))
    return SPACE_PATTERN.sub(" ", text).strip()


def license_allowed(short_name: str) -> bool:
    """Return True for CC0 / public domain / CC BY / CC BY-SA only."""
    norm = SPACE_PATTERN.sub(" ", short_name.strip().lower())
    if not norm or re.search(r"\b(nc|nd)\b", norm):
        return False
    return any(p.search(norm) for p in ALLOWED_LICENSE_PATTERNS)


def credit_line_ko(author: str, license_short: str) -> str:
    """Korean ready-to-paste credit line."""
    return f"사진: {author}, {license_short}, Wikimedia Commons"


def _api_get(params: dict[str, str | int]) -> dict[str, Any]:
    query = urllib.parse.urlencode({**params, "format": "json", "formatversion": 2})
    req = urllib.request.Request(f"{API_URL}?{query}", headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(req, timeout=HTTP_TIMEOUT_S) as resp:
            data = json.loads(resp.read().decode("utf-8"))
    except (urllib.error.URLError, TimeoutError, json.JSONDecodeError) as exc:
        raise FetchError(f"Commons API request failed: {exc}") from exc
    if "error" in data:
        raise FetchError(f"Commons API error: {data['error']}")
    return data


def _meta(ext: dict[str, Any], key: str) -> str:
    value = ext.get(key, {})
    return str(value.get("value", "")) if isinstance(value, dict) else ""


def parse_page(page: dict[str, Any]) -> Photo | None:
    """Convert an API page to Photo; None if it has no imageinfo."""
    infos = page.get("imageinfo") or []
    if not infos:
        return None
    info = infos[0]
    ext = info.get("extmetadata") or {}
    title = str(page["title"])
    haystack = " ".join(
        [title, _meta(ext, "Categories"), _meta(ext, "ImageDescription"), _meta(ext, "ObjectName")]
    )
    author = strip_html(_meta(ext, "Artist")) or "Unknown"
    return Photo(
        title=title,
        width=int(info.get("width", 0)),
        height=int(info.get("height", 0)),
        author=author,
        license_short=strip_html(_meta(ext, "LicenseShortName")),
        license_url=strip_html(_meta(ext, "LicenseUrl")),
        thumb_url=str(info.get("thumburl") or info.get("url", "")),
        page_url=str(info.get("descriptionurl", "")),
        mime=str(info.get("mime", "")),
        ai_flagged=bool(AI_PATTERN.search(haystack)),
    )


def search_photos(query: str, limit: int) -> list[Photo]:
    """Search Commons; returns at most `limit` real jpeg photos with allowed licenses."""
    if limit < 1:
        raise ValueError("limit must be >= 1")
    data = _api_get(
        {
            "action": "query",
            "generator": "search",
            "gsrnamespace": FILE_NAMESPACE,
            "gsrsearch": f"{query} filetype:bitmap",
            "gsrlimit": min(limit * OVERFETCH_FACTOR, MAX_API_LIMIT),
            "prop": "imageinfo",
            "iiprop": "url|extmetadata|mime|size",
            "iiurlwidth": THUMB_WIDTH,
        }
    )
    pages = sorted(data.get("query", {}).get("pages", []), key=lambda p: p.get("index", 0))
    out: list[Photo] = []
    for page in pages:
        photo = parse_page(page)
        if photo is None or photo.mime not in ALLOWED_MIME or photo.ai_flagged:
            continue
        if not license_allowed(photo.license_short):
            continue
        out.append(photo)
        if len(out) >= limit:
            break
    return out


def get_photo(title: str) -> Photo:
    """Fetch metadata for one file title and verify it is acceptable."""
    if not title.startswith("File:"):
        title = f"File:{title}"
    data = _api_get(
        {
            "action": "query",
            "titles": title,
            "prop": "imageinfo",
            "iiprop": "url|extmetadata|mime|size",
            "iiurlwidth": THUMB_WIDTH,
        }
    )
    pages = data.get("query", {}).get("pages", [])
    photo = parse_page(pages[0]) if pages else None
    if photo is None:
        raise FetchError(f"No such file on Commons: {title}")
    if photo.mime not in ALLOWED_MIME:
        raise FetchError(f"Not a jpeg photograph (mime={photo.mime}): {title}")
    if photo.ai_flagged:
        raise FetchError(f"Metadata mentions AI generation, refusing: {title}")
    if not license_allowed(photo.license_short):
        raise LicenseRefused(f"License '{photo.license_short}' is not CC0/PD/CC BY/CC BY-SA: {title}")
    return photo


def safe_filename(title: str) -> str:
    """Filesystem-safe name from a Commons title."""
    name = title.removeprefix("File:")
    name = re.sub(r"[^\w.\-]+", "_", name, flags=re.UNICODE).strip("_")
    return name or "photo.jpg"


def append_credit(out_dir: Path, filename: str, photo: Photo) -> Path:
    """Append a row to CREDITS.md, creating it with a header if needed."""
    path = out_dir / CREDITS_FILENAME
    if not path.exists():
        path.write_text(CREDITS_HEADER, encoding="utf-8")
    cells = [filename, photo.author, photo.license_short, photo.license_url, photo.page_url]
    row = "| " + " | ".join(c.replace("|", "\\|") for c in cells) + " |\n"
    with path.open("a", encoding="utf-8") as fh:
        fh.write(row)
    return path


def download(photo: Photo, out_dir: Path) -> Path:
    """Download the 1920px thumbnail and record credits. Returns the image path."""
    out_dir.mkdir(parents=True, exist_ok=True)
    dest = out_dir / safe_filename(photo.title)
    req = urllib.request.Request(photo.thumb_url, headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(req, timeout=HTTP_TIMEOUT_S) as resp:
            dest.write_bytes(resp.read())
    except (urllib.error.URLError, TimeoutError) as exc:
        raise FetchError(f"Download failed: {exc}") from exc
    append_credit(out_dir, dest.name, photo)
    return dest


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("search", help="search Commons for real photographs")
    s.add_argument("query")
    s.add_argument("-n", type=int, default=8, help="max results (default 8)")
    g = sub.add_parser("get", help="download one file and record credits")
    g.add_argument("title", help='e.g. "File:Example.jpg"')
    g.add_argument("--out", type=Path, required=True, help="assets directory")
    return parser


def main(argv: list[str] | None = None) -> int:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    args = build_parser().parse_args(argv)
    try:
        if args.cmd == "search":
            for p in search_photos(args.query, args.n):
                LOG.info("%s | %dx%d | %s | %s", p.title, p.width, p.height, p.author, p.license_short)
            return 0
        photo = get_photo(args.title)
        path = download(photo, args.out)
        LOG.info("saved %s", path)
        LOG.info("%s", credit_line_ko(photo.author, photo.license_short))
        return 0
    except (FetchError, ValueError) as exc:
        LOG.error("%s", exc)
        return 1


if __name__ == "__main__":
    sys.exit(main())
